// Generate the transport API from the engine's committed RPC schema and VERSION.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

type node struct {
	Ref        string          `json:"$ref"`
	Type       string          `json:"type"`
	Format     string          `json:"format"`
	Properties map[string]node `json:"properties"`
	Required   []string        `json:"required"`
	Items      *node           `json:"items"`
	Enum       []string        `json:"enum"`
	AllOf      []node          `json:"allOf"`
	AnyOf      []node          `json:"anyOf"`
	OneOf      []node          `json:"oneOf"`
}

func main() {
	check := flag.Bool("check", false, "fail if generated API differs")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func read(path string) ([]byte, error) { return os.ReadFile(path) }

func run(check bool) error {
	schema, err := read("../../docs/protocol/dctx-rpc-v1.schema.json")
	if err != nil {
		return err
	}
	version, err := read("../../VERSION")
	if err != nil {
		return err
	}
	var root struct {
		Definitions map[string]node `json:"definitions"`
	}
	if err := json.Unmarshal(schema, &root); err != nil {
		return err
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// SPDX-License-Identifier: Apache-2.0\n// Code generated by go generate from docs/protocol/dctx-rpc-v1.schema.json; DO NOT EDIT.\n\npackage dctx\n\nimport (\"context\"; \"encoding/json\")\n\nconst Version = %q\nconst schemaSHA256 = %q\n\n", strings.TrimSpace(string(version)), fmt.Sprintf("%x", sha256.Sum256(schema)))
	b.WriteString("// Verb is an engine operation. Arguments retain CLI spelling.\ntype Verb string\nconst (\n")
	verbs := root.Definitions["Verb"].OneOf
	if len(verbs) == 0 {
		return fmt.Errorf("schema has no verbs")
	}
	for _, v := range verbs {
		if len(v.Enum) != 1 || v.Type != "string" {
			return fmt.Errorf("unsupported verb schema")
		}
		fmt.Fprintf(&b, "Verb%s Verb = %q\n", name(v.Enum[0]), v.Enum[0])
	}
	b.WriteString(")\n")
	for _, pair := range [][2]string{{"Request", "Request"}, {"Hello", "Hello"}, {"Error", "EngineError"}, {"Response", "Response"}} {
		n, ok := root.Definitions[pair[0]]
		if !ok {
			return fmt.Errorf("schema missing %s", pair[0])
		}
		fmt.Fprintf(&b, "// %s is the RPC %s envelope.\ntype %s struct {\n", pair[1], pair[0], pair[1])
		keys := make([]string, 0, len(n.Properties))
		for key := range n.Properties {
			keys = append(keys, key)
		}
		sort.Strings(keys)
		for _, key := range keys {
			typ, err := goType(n.Properties[key])
			if err != nil {
				return fmt.Errorf("%s.%s: %w", pair[0], key, err)
			}
			tag := key
			if !contains(n.Required, key) {
				tag += ",omitempty"
			}
			fmt.Fprintf(&b, "%s %s `json:%q`\n", name(key), typ, tag)
		}
		if pair[0] == "Response" {
			// Keep the two union arms raw until envelope validation. Pages stay opaque.
			if len(n.AnyOf) != 2 {
				return fmt.Errorf("unsupported response union")
			}
			for _, arm := range n.AnyOf {
				if len(arm.Properties) != 1 {
					return fmt.Errorf("unsupported response arm")
				}
				for key := range arm.Properties {
					fmt.Fprintf(&b, "%s json.RawMessage `json:%q`\n", name(key), key+",omitempty")
				}
			}
		}
		b.WriteString("}\n")
	}
	result := root.Definitions["ResultBody"]
	if len(result.AnyOf) != 2 {
		return fmt.Errorf("unsupported result union")
	}
	out := result.AnyOf[1]
	if len(out.Properties) != 1 || out.Properties["output"].Type != "string" || !contains(out.Required, "output") {
		return fmt.Errorf("unsupported output schema")
	}
	b.WriteString("// Output contains exact CLI stdout, including trailing newlines.\ntype Output struct { Output string `json:\"output\"` }\n")
	for _, v := range verbs {
		verb := v.Enum[0]
		if verb == "hello" {
			continue
		}
		fmt.Fprintf(&b, "// %s forwards arguments unchanged to the %s engine operation.\nfunc (c *Client) %s(ctx context.Context, args ...string) ([]byte, error) { return c.Call(ctx, Verb%s, args...) }\n", name(verb), verb, name(verb), name(verb))
	}
	generated, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	if check {
		current, err := read("api_generated.go")
		if err != nil {
			return err
		}
		if !bytes.Equal(current, generated) {
			return fmt.Errorf("stale Go API: run go generate in packages/go")
		}
		return nil
	}
	return os.WriteFile("api_generated.go", generated, 0o644)
}

func name(s string) string {
	if s == "id" {
		return "ID"
	}
	parts := strings.Split(s, "_")
	for i, part := range parts {
		parts[i] = strings.ToUpper(part[:1]) + part[1:]
	}
	return strings.Join(parts, "")
}

func contains(values []string, value string) bool {
	for _, v := range values {
		if v == value {
			return true
		}
	}
	return false
}

func goType(n node) (string, error) {
	if len(n.AllOf) == 1 {
		return goType(n.AllOf[0])
	}
	if n.Ref != "" {
		ref := strings.TrimPrefix(n.Ref, "#/definitions/")
		if ref == "Id" {
			return "json.RawMessage", nil
		}
		if ref == "Verb" {
			return "Verb", nil
		}
		return "", fmt.Errorf("unsupported reference %s", n.Ref)
	}
	if len(n.AnyOf) > 0 { // Response ID union, string or signed int64.
		if len(n.AnyOf) != 2 || n.AnyOf[0].Type != "string" || n.AnyOf[1].Format != "int64" {
			return "", fmt.Errorf("unsupported union")
		}
		return "json.RawMessage", nil
	}
	switch n.Type {
	case "string":
		return "string", nil
	case "integer":
		return "int", nil
	case "array":
		if n.Items == nil {
			return "", fmt.Errorf("array has no items")
		}
		typ, err := goType(*n.Items)
		return "[]" + typ, err
	default:
		return "", fmt.Errorf("unsupported type %q", n.Type)
	}
}
