"""Generate wire types and verb methods from the engine's committed RPC schema."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SCHEMA = ROOT / "docs/protocol/dctx-rpc-v1.schema.json"
DEST = ROOT / "packages/python/src/dctx/_generated.py"


def generate() -> str:
    raw = SCHEMA.read_bytes()
    definitions = json.loads(raw)["definitions"]

    def wire_type(node: dict) -> str:
        if "$ref" in node:
            return node["$ref"].rsplit("/", 1)[-1]
        if "allOf" in node:
            assert len(node["allOf"]) == 1
            return wire_type(node["allOf"][0])
        for key in ("anyOf", "oneOf"):
            if key in node:
                return " | ".join(dict.fromkeys(wire_type(item) for item in node[key]))
        if "enum" in node:
            return "Literal[" + ", ".join(repr(item) for item in node["enum"]) + "]"
        kind = node["type"]
        if kind == "array":
            return f"list[{wire_type(node['items'])}]"
        return {"string": "str", "integer": "int", "null": "None"}[kind]

    def typed_dict(name: str, node: dict) -> list[str]:
        fields = []
        for key, value in node["properties"].items():
            annotation = wire_type(value)
            if key not in node.get("required", []):
                annotation = f"NotRequired[{annotation}]"
            fields.append(f"    {key}: {annotation}")
        return [f"class {name}(TypedDict):", *fields, "", ""]

    verbs = [item["enum"][0] for item in definitions["Verb"]["oneOf"]]
    result = definitions["ResultBody"]["anyOf"]
    assert len(result) == 2 and result[0]["allOf"][0]["$ref"] == "#/definitions/Hello"
    response = definitions["Response"]
    assert {tuple(case["required"]) for case in response["anyOf"]} == {("result",), ("error",)}
    lines = [
        "# SPDX-License-Identifier: Apache-2.0",
        "# Generated by tools/generate_api.py; do not edit.",
        f"# Schema SHA-256: {hashlib.sha256(raw).hexdigest()}",
        "from __future__ import annotations", "",
        "from typing import Literal, NotRequired, TypedDict", "",
        f"Id = {wire_type(definitions['Id'])}",
        f"Verb = {wire_type(definitions['Verb'])}", "", "",
    ]
    for name in ("Hello", "Error", "Request"):
        lines.extend(typed_dict(name, definitions[name]))
    lines.extend(typed_dict("Output", result[1]))
    lines += ["ResultBody = Hello | Output", "", ""]
    for name, field, annotation in (("Success", "result", "ResultBody"), ("Failure", "error", "Error")):
        lines += [f"class {name}(TypedDict):", "    id: Id | None",
                  f"    engine_version: {wire_type(response['properties']['engine_version'])}",
                  f"    {field}: {annotation}", "", ""]
    lines += ["Response = Success | Failure", "", "", "class Operations:",
              '    """Pass CLI argument strings unchanged; return exact engine stdout bytes."""', "",
              "    def _operation(self, verb: Verb, args: tuple[str, ...]) -> bytes:",
              "        raise NotImplementedError", ""]
    for verb in verbs:
        if verb == "hello":
            continue
        lines += [f"    def {verb}(self, *args: str) -> bytes:",
                  f"        return self._operation({verb!r}, args)", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = generate()
    if args.check:
        if not DEST.is_file() or DEST.read_text(encoding="utf-8") != output:
            parser.exit(1, "RPC Python API is stale; run python packages/python/tools/generate_api.py\n")
    else:
        DEST.write_text(output, encoding="utf-8")


if __name__ == "__main__":
    main()
