import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const schemaUrl = new URL('../../../docs/protocol/dctx-rpc-v1.schema.json', import.meta.url);
const destination = new URL('../dctx/src/protocol.d.ts', import.meta.url);
const bytes = readFileSync(schemaUrl);
const schema = JSON.parse(bytes);

// Deliberately fail on unhandled schema constructs rather than silently broadening types.
function type(node) {
  const allowed = new Set(['$ref', 'description', 'type', 'enum', 'anyOf', 'oneOf', 'allOf',
    'properties', 'required', 'items', 'default', 'format', 'minimum', 'maximum']);
  for (const key of Object.keys(node)) {
    if (!allowed.has(key)) throw new Error(`Unsupported RPC schema keyword: ${key}`);
  }
  const parts = [];
  if (node.$ref) {
    if (!node.$ref.startsWith('#/definitions/')) throw new Error(`Unsupported ref: ${node.$ref}`);
    parts.push(node.$ref.slice('#/definitions/'.length));
  }
  if (node.enum) parts.push(node.enum.map((value) => JSON.stringify(value)).join(' | '));
  for (const key of ['anyOf', 'oneOf', 'allOf']) {
    if (node[key]) parts.push(`(${node[key].map(type).join(key === 'allOf' ? ' & ' : ' | ')})`);
  }
  if (node.type === 'object') {
    parts.push(`{ ${Object.entries(node.properties ?? {}).map(([name, value]) =>
      `${JSON.stringify(name)}${node.required?.includes(name) ? '' : '?'}: ${type(value)};`).join(' ')} }`);
  } else if (!node.enum && node.type) {
    switch (node.type) {
      case 'array': parts.push(`Array<${type(node.items)}>`); break;
      case 'integer': case 'number': parts.push('number'); break;
      case 'string': case 'boolean': case 'null': parts.push(node.type); break;
      default: throw new Error(`Unsupported RPC schema type: ${node.type}`);
    }
  }
  if (!parts.length) throw new Error(`Empty RPC schema type: ${JSON.stringify(node)}`);
  return parts.join(' & ');
}
const output = '// SPDX-License-Identifier: Apache-2.0\n' +
  '// Generated by packaging/npm/scripts/generate-types.mjs. Do not edit.\n' +
  `// RPC schema SHA-256: ${createHash('sha256').update(bytes).digest('hex')}\n\n` +
  Object.entries(schema.definitions).map(([name, node]) =>
    `${node.description ? `/** ${node.description.replaceAll('*/', '* /')} */\n` : ''}export type ${name} = ${type(node)};\n`).join('\n');
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== output) throw new Error('Stale RPC types: run node packaging/npm/scripts/generate-types.mjs');
} else {
  writeFileSync(destination, output);
}
