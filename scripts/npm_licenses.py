"""Write or check THIRD_PARTY_NPM.md from the repository's npm lockfiles.

Every package entry in every package-lock.json is included, except the root
project entry and lockfiles below node_modules. License expressions use the
same allow-list and evaluator as scripts/third_party.py.

With no arguments (or --out FILE), write the report even when owner decisions
are needed. --check compares a temporary report with the committed file and
fails for staleness or for a missing/disallowed license not already recorded
in the committed report's "Needs owner decision" section.
"""

import argparse
import difflib
import json
import os
import sys
import tempfile
from pathlib import Path
from typing import NamedTuple

from third_party import ALLOWED, license_allowed

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = ROOT / "THIRD_PARTY_NPM.md"
MISSING = "(missing)"
DECISION_HEADING = "## Needs owner decision"


class Package(NamedTuple):
    lockfile: str
    path: str
    name: str
    version: str
    license: str


def find_lockfiles():
    """Return all repository lockfiles, pruning node_modules and .git."""
    lockfiles = []
    for directory, dirnames, filenames in os.walk(ROOT):
        dirnames[:] = sorted(name for name in dirnames if name not in ("node_modules", ".git"))
        if "package-lock.json" in filenames:
            path = Path(directory) / "package-lock.json"
            lockfiles.append((path.relative_to(ROOT).as_posix(), path))
    return sorted(lockfiles)


def load_lockfile(lockfile, path):
    """Read third-party package entries from one lockfile."""
    data = json.loads(path.read_text(encoding="utf-8"))
    packages = data.get("packages")
    if not isinstance(packages, dict):
        raise ValueError(f"{lockfile}: no packages object (lockfileVersion 2 or later is required)")

    rows = []
    for package_path, entry in packages.items():
        if not package_path:  # The lockfile's root describes this repository, not a third party.
            continue
        if not isinstance(entry, dict):
            raise ValueError(f"{lockfile}: package entry {package_path!r} is not an object")
        name = entry.get("name") or package_path.rsplit("node_modules/", 1)[-1]
        version = entry.get("version") or MISSING
        license_expression = entry.get("license")
        if license_expression is None:
            license_expression = ""
        elif not isinstance(license_expression, str):
            license_expression = json.dumps(license_expression, sort_keys=True)
        rows.append(Package(lockfile, package_path, str(name), str(version), license_expression))
    return rows


def load_packages():
    """Read every repository lockfile and return all package rows."""
    rows = []
    for lockfile, path in find_lockfiles():
        rows.extend(load_lockfile(lockfile, path))
    return rows


def allowed(package):
    return bool(package.license.strip()) and license_allowed(package.license)


def cell(value):
    """Escape a value for one deterministic Markdown table cell."""
    text = value if value and value.strip() else MISSING
    return text.replace("\\", "\\\\").replace("|", "\\|").replace("\r", " ").replace("\n", " ")


def package_sort_key(package):
    return package.name, package.version, package.path


def decision_row(package):
    return (
        f"| {cell(package.lockfile)} | {cell(package.name)} | {cell(package.version)} "
        f"| {cell(package.license)} |"
    )


def render(rows):
    """Render summary counts, owner decisions, and one sorted table per lockfile."""
    lockfiles = sorted({package.lockfile for package in rows})
    decisions = sorted((package for package in rows if not allowed(package)), key=lambda p: (p.lockfile, package_sort_key(p)))
    lines = [
        "# Third-party npm dependencies",
        "",
        "Generated by `scripts/npm_licenses.py` from every repository `package-lock.json`; do not edit by hand.",
        "The root project entry in each lockfile is omitted. Each package keeps its own license and notices; this is an index, not the license texts.",
        "",
        "## Summary",
        "",
        "| Lockfile | Packages | Allowed | Needs owner decision |",
        "|---|---:|---:|---:|",
    ]
    for lockfile in lockfiles:
        group = [package for package in rows if package.lockfile == lockfile]
        denied = sum(not allowed(package) for package in group)
        lines.append(f"| {cell(lockfile)} | {len(group)} | {len(group) - denied} | {denied} |")
    lines.extend([
        f"| **Total** | **{len(rows)}** | **{len(rows) - len(decisions)}** | **{len(decisions)}** |",
        "",
        "Allowed licenses (and OR/AND combinations of them): " + ", ".join(ALLOWED) + ".",
        "An OR expression passes when at least one branch is allowed; an AND expression requires every branch to be allowed.",
        "",
        DECISION_HEADING,
        "",
    ])
    if decisions:
        lines.extend([
            "These exact entries are recorded for an owner decision. `--check` fails for any new or changed entry not present here.",
            "",
            "| Lockfile | Package | Version | License |",
            "|---|---|---|---|",
        ])
        lines.extend(decision_row(package) for package in decisions)
    else:
        lines.append("None.")
    for lockfile in lockfiles:
        group = sorted((package for package in rows if package.lockfile == lockfile), key=package_sort_key)
        lines.extend([
            "",
            f"## `{lockfile}`",
            "",
            "| Package | Version | License |",
            "|---|---|---|",
        ])
        lines.extend(f"| {cell(package.name)} | {cell(package.version)} | {cell(package.license)} |" for package in group)
    return "\n".join(lines) + "\n"


def acknowledged_rows(text):
    """Return the exact package rows in the committed owner-decision section."""
    lines = text.splitlines()
    try:
        start = lines.index(DECISION_HEADING) + 1
    except ValueError:
        return set()
    acknowledged = set()
    for line in lines[start:]:
        if line.startswith("## "):
            break
        if line.startswith("| "):
            acknowledged.add(line)
    return acknowledged


def new_decisions(rows, committed_text):
    """Return current license problems lacking an exact committed decision row."""
    acknowledged = acknowledged_rows(committed_text)
    return [package for package in rows if not allowed(package) and decision_row(package) not in acknowledged]


def print_decisions(decisions):
    for package in sorted(decisions, key=lambda p: (p.lockfile, package_sort_key(p))):
        location = f"{package.lockfile}: {package.name} {package.version}"
        if package.license.strip():
            print(f"  {location}: license {package.license!r} is not on the allow-list", file=sys.stderr)
        else:
            print(f"  {location}: no license expression (license field missing or empty)", file=sys.stderr)


def check(rows, out):
    """Regenerate to a temporary file, diff it, and reject unrecorded decisions."""
    generated = render(rows)
    try:
        committed = out.read_text(encoding="utf-8")
    except FileNotFoundError:
        committed = ""
        print(f"npm_licenses FAIL: committed report {out} is missing", file=sys.stderr)

    failed = False
    decisions = new_decisions(rows, committed)
    if decisions:
        print(f"npm_licenses FAIL: {len(decisions)} package(s) need an unrecorded owner decision:", file=sys.stderr)
        print_decisions(decisions)
        failed = True

    with tempfile.TemporaryDirectory(prefix="npm_licenses-") as directory:
        temporary = Path(directory) / "THIRD_PARTY_NPM.md"
        temporary.write_text(generated, encoding="utf-8")
        regenerated = temporary.read_text(encoding="utf-8")
        if committed != regenerated:
            print(f"npm_licenses FAIL: {out} is stale; run `python3 scripts/npm_licenses.py`", file=sys.stderr)
            sys.stdout.writelines(difflib.unified_diff(
                committed.splitlines(keepends=True),
                regenerated.splitlines(keepends=True),
                fromfile=f"{out} (committed)",
                tofile=f"{out} (generated)",
            ))
            failed = True

    if failed:
        return 1
    decision_count = sum(not allowed(package) for package in rows)
    print(f"npm_licenses ok: {len(rows)} packages, {decision_count} recorded owner decision(s); {out} is up to date")
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--out", type=Path, default=DEFAULT_OUT, help=f"report path (default: {DEFAULT_OUT})")
    mode.add_argument("--check", action="store_true", help="check the committed THIRD_PARTY_NPM.md without changing it")
    args = parser.parse_args(argv)
    try:
        rows = load_packages()
    except (OSError, ValueError) as error:
        print(f"npm_licenses: {error}", file=sys.stderr)
        return 2
    if args.check:
        return check(rows, DEFAULT_OUT)

    generated = render(rows)
    try:
        args.out.write_text(generated, encoding="utf-8")
    except OSError as error:
        print(f"npm_licenses: {error}", file=sys.stderr)
        return 2
    decisions = sum(not allowed(package) for package in rows)
    print(f"npm_licenses: wrote {len(rows)} packages to {args.out}; {decisions} owner decision(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
