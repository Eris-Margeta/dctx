#!/usr/bin/env python3
"""Render the README benchmark block from the committed benchmark JSON (v1 card 7).

Usage: python3 scripts/render_readme.py [--check]

Reads the run 7 three-way aggregate and the task-protocol aggregate under
docs/research/bench-3way-20261030/ and writes the text between
`<!-- bench:begin -->` and `<!-- bench:end -->` in README.md. `--check` writes
nothing and exits 1 when the committed block differs from the rendered one.
Standard library only; run from any directory.
"""

import datetime
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
BENCH = "docs/research/bench-3way-20261030"
AGGREGATE = f"{BENCH}/results/run7-53f8b6b/aggregate.json"
TASKS = f"{BENCH}/tasks/results/run5-53f8b6b/tasks_aggregate.json"
BEGIN = "<!-- bench:begin -->\n"
END = "<!-- bench:end -->"
# The six benchmark corpora; the canary fixtures are privacy probes, not timing corpora.
CORPORA = ("flask", "ripgrep", "pocketbase", "trailcode", "mixed", "docs")
TOOLS = (("dctx", "dctx"), ("trail", "Trail-Code"), ("graphify", "graphify"))
ESTIMATOR = "ceil(stdout_bytes/3.5)"


def load(relative):
    """Returns the parsed JSON file at `relative` under the repository root."""
    with open(ROOT / relative, encoding="utf-8") as handle:
        return json.load(handle)


def num(value):
    """Formats an integer with thousands separators."""
    return f"{value:,}"


def seconds(walls):
    """Formats the min–max of cold index walls in seconds, two decimals."""
    return f"{min(walls):.2f}–{max(walls):.2f} s"


def run_date(meta):
    """Returns the run date of the aggregate as `31 Oct 2026`."""
    day = datetime.date.fromisoformat(meta["date_utc"][:10])
    month = ("Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec")[day.month - 1]
    return f"{day.day} {month} {day.year}"


def cold_walls(index, tool):
    """Returns the median cold index walls of `tool` on the corpora it indexed, and the corpora it failed."""
    walls, failed = [], []
    for corpus in CORPORA:
        row = index[corpus][tool]
        if row.get("ok") and row.get("cold_wall_s_median") is not None:
            walls.append(row["cold_wall_s_median"])
        else:
            failed.append(corpus)
    if not walls:
        sys.exit(f"render_readme: no cold index walls for {tool}")
    return walls, failed


def render():
    """Returns the rendered benchmark block, without the begin and end markers."""
    agg, tasks = load(AGGREGATE), load(TASKS)
    meta, overall = agg["meta"], tasks["overall"]
    if meta["token_estimator"] != ESTIMATOR:
        sys.exit(f"render_readme: unexpected token estimator {meta['token_estimator']!r}")
    trail = meta["trail_version"]
    graphify = meta["graphify_version"].removeprefix("graphify ").strip()
    commit = AGGREGATE.split("/")[-2].split("-")[-1]
    dctx, tc, gf = overall["dctx"], overall["trail"], overall["graphify"]
    for row in (dctx, tc, gf):
        if row["max_score"] != dctx["max_score"] or row["facts_total"] != dctx["facts_total"]:
            sys.exit("render_readme: the tools were scored on different protocols")
    questions, points, facts = dctx["questions"], dctx["max_score"], dctx["facts_total"]
    when = run_date(meta)
    out = [
        f"<!-- Generated by scripts/render_readme.py from {AGGREGATE} and {TASKS}. Edit the script, then run it; `just readme-check` fails on drift. -->",
        "",
        f"On our {questions}-question protocol (designed by the dctx team; questions, gold facts and scorer are in "
        f"[`{BENCH}/tasks/`]({BENCH}/tasks/)), run {when} against Trail-Code {trail} and graphify {graphify} in code-only mode, "
        f"dctx scored {dctx['score']}/{points} using {num(dctx['tokens'])} tokens; Trail-Code {tc['score']} ({num(tc['tokens'])}), "
        f"graphify {gf['score']} ({num(gf['tokens'])}). Tokens are estimated as stdout bytes / 3.5, rounded up, for every tool.",
        "",
        f"| Tool | Points /{points} | Gold facts /{facts} | Tokens | Tool calls |",
        "|---|---|---|---|---|",
    ]
    labels = {"dctx": f"dctx `{commit}`", "trail": f"Trail-Code {trail}", "graphify": f"graphify {graphify}, code-only"}
    for key, _ in TOOLS:
        row = overall[key]
        out.append(f"| {labels[key]} | {row['score']} | {row['facts_found']} | {num(row['tokens'])} | {row['calls']} |")
    out += [
        "",
        "That protocol is ours, so it can favour dctx. A separate [independent benchmark](docs/research/bench-independent/README.md) "
        "uses seeded repository selection and language-server caller gold. It reports lower caller recall on unseen repositories; "
        "the curated-corpus results above do not establish the same accuracy elsewhere.",
        "",
    ]
    parts = []
    for key, name in TOOLS:
        walls, failed = cold_walls(agg["index"], key)
        note = f" ({', '.join(failed)}: no index)" if failed else ""
        parts.append(f"{name} {seconds(walls)}{note}")
    out += [
        f"Cold index of the {len(CORPORA)} benchmark corpora ({', '.join(CORPORA)}; median of {agg['index'][CORPORA[0]]['dctx']['n_reps']} runs) "
        f"took {parts[0]}, against {parts[1]} and {parts[2]}, on one Linux x86_64 runner ({meta['host_kernel']}, {meta['cpu_model']}). "
        "These performance measurements cover Linux x86_64 only; [CI covers Linux, macOS and Windows](docs/TESTING.md).",
        "",
    ]
    steps = [row for row in agg["network"] if row["tool"] == "dctx"]
    if not steps or any(row["socket_calls"] or row["inet_attempt_count"] for row in steps):
        sys.exit("render_readme: the dctx network rows are missing or not zero")
    out += [
        f"dctx makes no network calls: it made 0 socket calls in all {len(steps)} traced benchmark steps, and the release check "
        "(`scripts/release-check.sh`) asserts zero AF_INET/AF_INET6 connect/send calls under `strace -f` for every map verb, "
        "`pack`, `cache status` and `mcp`.",
        "",
        f"Raw results, corpora pins and scripts: [`{BENCH}/`]({BENCH}/); the write-up is [docs/BENCHMARK-20261030.md](docs/BENCHMARK-20261030.md) (Run 7).",
    ]
    return "\n".join(out) + "\n"


def splice(readme, block):
    """Returns `readme` with the text between the bench markers replaced by `block`."""
    if readme.count(BEGIN) != 1 or readme.count(END) != 1:
        sys.exit("render_readme: README.md needs exactly one bench:begin and one bench:end marker")
    head, rest = readme.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + BEGIN + block + END + tail


def main(argv):
    """Writes the README block, or with `--check` compares it; returns the exit code."""
    if argv not in ([], ["--check"]):
        print("Usage: render_readme.py [--check]", file=sys.stderr)
        return 2
    readme = README.read_text(encoding="utf-8")
    rendered = splice(readme, render())
    if argv == ["--check"]:
        if rendered != readme:
            print("README.md bench block differs from the rendered one; run python3 scripts/render_readme.py", file=sys.stderr)
            return 1
        print("README.md bench block matches the benchmark JSON")
        return 0
    if rendered != readme:
        README.write_text(rendered, encoding="utf-8")
        print("Updated README.md bench block")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
