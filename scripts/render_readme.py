#!/usr/bin/env python3
"""Render README measurements, captured output and the compiled library example.

Usage: python3 scripts/render_readme.py [--check]

Uses the whole-session results documented in docs/BENCHMARK-20261111.md
and cold timings from the run 7 aggregate, and writes the text between
`<!-- bench:begin -->` and `<!-- bench:end -->` in README.md. Output examples come
from tools/website/data/demo.json; the library snippet comes from its doctest.
`--check` writes nothing and exits 1 when any generated block drifts.
Standard library only; run from any directory.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools/website"))
from output_examples import render as render_output  # noqa: E402

README = ROOT / "README.md"
BENCH = "docs/research/bench-3way-20261030"
AGGREGATE = f"{BENCH}/results/run7-53f8b6b/aggregate.json"
BEGIN = "<!-- bench:begin -->\n"
END = "<!-- bench:end -->"
# The six benchmark corpora; the canary fixtures are privacy probes, not timing corpora.
CORPORA = ("flask", "ripgrep", "pocketbase", "trailcode", "mixed", "docs")


def load(relative):
    """Returns the parsed JSON file at `relative` under the repository root."""
    with open(ROOT / relative, encoding="utf-8") as handle:
        return json.load(handle)


def seconds(walls):
    """Formats the min–max of cold index walls in seconds, two decimals."""
    return f"{min(walls):.2f}–{max(walls):.2f} s"


def cold_walls(index, tool):
    """Returns the median cold index walls of `tool` on the corpora it indexed, and the corpora it failed."""
    walls, failed = [], []
    for corpus in CORPORA:
        row = index[corpus][tool]
        if row.get("ok") and row.get("cold_wall_s_median") is not None:
            walls.append(row["cold_wall_s_median"])
        else:
            failed.append(corpus)
    if not walls:
        sys.exit(f"render_readme: no cold index walls for {tool}")
    return walls, failed


def render():
    """Render the grep/read baseline and a scoped historical timing from evidence."""
    agg = load(AGGREGATE)
    walls, _ = cold_walls(agg["index"], "dctx")
    return "\n".join([
        "<!-- Generated by scripts/render_readme.py. Whole-session results: docs/BENCHMARK-20261111.md; historical timing: " + AGGREGATE + ". -->",
        "",
        "The baseline is **grep plus reading files**.",
        "",
        "The [11 November whole-session benchmark](docs/BENCHMARK-20261111.md) measured 20 questions on a private "
        "13-crate Rust workspace with `claude-sonnet-5-5`, dctx 1.3.0 and three repeats per arm. "
        "Median total tokens [min, max]: grep plus reads 14,904,014 [14,604,149, 15,622,381]; "
        "dctx CLI (warm index) 14,157,974 [11,221,908, 15,613,375].",
        "",
        "**On this corpus and model dctx did not save 25 % tokens.** CLI median tokens were -5.01 % versus grep; "
        "the pre-registered success rule was not met. "
        "The claim is **accuracy and bounded context**, not token savings: CLI named more required files "
        "at about equal or higher token cost.",
        "",
        "dctx on its own does not save tokens by default. Savings come from a harness or agent system "
        "that reuses byte-identical, prefix-stable context across long sessions over a large body of work. "
        "It behaves like an advanced caching mechanism, with complete control over every byte of context. "
        "There is no measured, citable savings figure for such a system yet. "
        "[Why this matters](docs/WHY-DCTX.md#savings-belong-to-the-system).",
        "",
        "Official strict citation recall medians [min, max]: grep 10.10 % [10.10, 20.73], "
        "CLI 14.46 % [8.36, 22.65]. Diagnostic file-level recall medians: "
        "53.77 % and 71.70 %, respectively; this does not replace strict recall. "
        "One corpus, one model, three repeats; no significance claim. Corpus and raw answers are private "
        "and cannot be published; dctx 1.3.0 is not current HEAD. **Under ~200 files, use grep.**",
        "",
        f"Historical cold indexing of six benchmark corpora took dctx {seconds(walls)} on one Linux x86_64 runner. "
        "This measures CLI wall time, not agent completion time or session cost.",
        "",
        "[Choosing how to use dctx](docs/MODALITIES.md) covers scoping and CLI usage. "
        "[Measurement evidence](docs/BENCHMARK-20261030.md) describes what was measured (tool-output "
        "bytes and estimated tokens); other-tool protocols are retained only as secondary historical notes.",
    ]) + "\n"


def splice(readme, block, begin=BEGIN, end=END):
    """Replace exactly one generated block, refusing missing or duplicate markers."""
    if readme.count(begin) != 1 or readme.count(end) != 1:
        sys.exit(f"render_readme: README.md needs exactly one {begin.strip()} and one {end} marker")
    head, rest = readme.split(begin, 1)
    _, tail = rest.split(end, 1)
    return head + begin + block + end + tail


def library_example():
    """Visible lines of the compiled Rust doctest, without rustdoc's hidden annotation."""
    source = (ROOT / "examples/library/README.md").read_text(encoding="utf-8")
    snippet = source.split("```rust\n", 1)[1].split("```", 1)[0]
    visible = "\n".join(line for line in snippet.splitlines() if not line.startswith("# "))
    return "```rust\n" + visible + "\n```\n"


def main(argv):
    """Writes the README block, or with `--check` compares it; returns the exit code."""
    if argv not in ([], ["--check"]):
        print("Usage: render_readme.py [--check]", file=sys.stderr)
        return 2
    readme = README.read_text(encoding="utf-8")
    rendered = splice(readme, render())
    rendered = splice(rendered, render_output(load("tools/website/data/demo.json")["records"]),
                      "<!-- output:begin -->\n", "<!-- output:end -->")
    rendered = splice(rendered, library_example(), "<!-- library:begin -->\n", "<!-- library:end -->")
    if argv == ["--check"]:
        if rendered != readme:
            print("README.md generated blocks differ; run python3 scripts/render_readme.py", file=sys.stderr)
            return 1
        print("README.md measurement, output and library blocks match their generators")
        return 0
    if rendered != readme:
        README.write_text(rendered, encoding="utf-8")
        print("Updated README.md generated blocks")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
