#!/bin/sh
# Usage: zsh tools/sync-version.sh [--check|--write]
# VERSION governs every crates/* and plugins/* package, their Cargo.lock entries,
# project metadata, the README badge, the Python wrapper version files, the Go
# generated Version const (--write reruns `go generate` in packages/go when Go is
# installed) and the vX.Y.Z release links and install pins in the docs and package
# READMEs, and the committed npm package manifests (the release rewrites copies of
# them from the tag with tools/release/prepare-npm.py).
# The desktop app keeps its own version line.
set -eu

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
if [ "$#" -gt 1 ]; then
  printf '%s\n' "Usage: $0 [--check|--write]" >&2
  exit 2
fi
MODE="${1:---check}"
if [ "$MODE" != --check ] && [ "$MODE" != --write ]; then
  printf '%s\n' "Usage: $0 [--check|--write]" >&2
  exit 2
fi

python3 - "$SCRIPT_DIR/.." "$MODE" <<'PYTHON'
import re
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

root = Path(sys.argv[1]).resolve()
mode = sys.argv[2]
version = (root / "VERSION").read_text().strip()
if not re.fullmatch(r"(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)", version):
    sys.exit("VERSION must contain a stable X.Y.Z release version")

patterns = {
    "project-meta.yaml": (r'(?m)^(version: ")[^"]+("[ \t]*)$', rf'\g<1>{version}\2'),
}
# Version mentions outside Cargo: (file, pattern, at least this many matches).
# Group 1 is kept, the version replaces V, group 2 (when present) is kept.
V = r"\d+\.\d+\.\d+"
RELEASE_LINK = r"(Eris-Margeta/dctx/releases/tag/v)" + V + r"()"
GIT_TAG_PIN = r'(tag = "v)' + V + r'(")'
mentions = [
    ("README.md", r"(https://img.shields.io/badge/version-)" + V + r"()", 1),
    ("README.md", RELEASE_LINK, 1),
    ("README.md", GIT_TAG_PIN, 1),
    ("docs/MODALITIES.md", RELEASE_LINK, 1),
    ("docs/MODALITIES.md", GIT_TAG_PIN, 1),
    ("docs/START.md", RELEASE_LINK, 1),
    ("docs/VERIFYING.md", r"(?m)(^TAG=v)" + V + r"()", 1),
    ("docs/README.md", r"(current release is\s+)" + V + r"()", 1),
    ("packages/go/README.md", RELEASE_LINK, 1),
    ("packages/go/README.md", r"(\[v)" + V + r"( releases\])", 1),
    ("packages/go/README.md", r"(--tag v)" + V + r"( dctx-cli)", 1),
    ("packages/go/README.md", r"(packages/go[ /@]v)" + V + r"()", 1),
    ("packages/go/README.md", r"(engine \*\*)" + V + r"(\*\*)", 1),
    ("packages/go/README.md", r"(dctx/bin/)" + V + r"(/)", 1),
    ("packages/python/README.md", r"(dctx(?:\[binary\])?==)" + V + r"()", 1),
    ("packages/python/README.md", r"(release \(`)" + V + r"(`\))", 1),
    ("packages/python/README.md", r"(dctx/bin/)" + V + r"(/)", 1),
    ("packages/python/pyproject.toml", r'(?ms)(^\[project\]\n(?:(?!^\[).)*?^version = ")' + V + r'(")', 1),
    ("packages/python/pyproject.toml", r"(dctx-binary-[a-z0-9-]+==)" + V + r"()", 5),
    ("packages/python/src/dctx/_version.py", r'(?m)(^__version__ = ")' + V + r'(")', 1),
    # Generated by `go generate` from VERSION; --write also reruns the generator.
    ("packages/go/api_generated.go", r'(?m)(^const Version = ")' + V + r'(")', 1),
    # The npm client requires engine_version == its package.json version, so the
    # committed manifests (and the parity tests run against them) follow VERSION.
    # prepare-npm.py rewrites copies of them from the tag at release time.
    ("packaging/npm/dctx/package.json", r'(?m)(^  "version": ")' + V + r'(")', 1),
    ("packaging/npm/dctx/package.json", r'("@dctx/cli-[a-z0-9-]+": ")' + V + r'(")', 5),
    ("packaging/npm/README.md", r"(prepare-npm\.py v)" + V + r"()", 1),
    ("docs/protocol/README.md", r'("engine_version":")' + V + r'(")', 1),
    # The website facts source; check.py also compares "released" with CHANGELOG.md.
    ("tools/website/data/facts.json", r'(?m)(^ "version": ")' + V + r'(")', 1),
    ("tools/website/data/facts.json", r'(?m)(^ "release_tag": "v)' + V + r'(")', 1),
    ("tools/website/data/facts.json", RELEASE_LINK, 1),
    ("tools/website/data/facts.json", r'(tag = \\"v)' + V + r'(\\")', 1),
]
for npm_platform in ("darwin-arm64", "darwin-x64", "linux-arm64", "linux-x64", "win32-x64"):
    mentions.append((f"packaging/npm/cli-{npm_platform}/package.json", r'(?m)(^  "version": ")' + V + r'(")', 1))
lock = []
for manifest in sorted([*root.glob("crates/*/Cargo.toml"), *root.glob("plugins/*/Cargo.toml")]):
    # Stay inside [package]; never rewrite dependency version requirements.
    patterns[manifest.relative_to(root).as_posix()] = (
        r'(?ms)(^\[package\]\n(?:(?!^\[).)*?^version = ")[^"]+("[ \t]*$)',
        rf'\g<1>{version}\2',
    )
    name = re.search(r'(?ms)^\[package\]\n(?:(?!^\[).)*?^name = "([^"]+)"', manifest.read_text())
    if not name:
        sys.exit(f"No package name in {manifest.relative_to(root)}")
    lock.append(name.group(1))
# Workspace package names only; no registry crate shares a name with a workspace package.
lock_pattern = r'(?m)(^\[\[package\]\]\nname = "(?:' + "|".join(map(re.escape, lock)) + r')"\nversion = ")[^"]+(")'

# Registry requirements must follow the package versions for the next release.
# Versionless dev-only path dependencies are intentionally omitted by Cargo when
# packaging; adding registry versions there would create publication cycles.
manifests = sorted([*root.glob("crates/*/Cargo.toml"), *root.glob("plugins/*/Cargo.toml")])
local_dirs = {p.parent.resolve() for p in manifests}

# Validate every expected field before writing any file.
updates = []
lock_path = root / "Cargo.lock"
before = lock_path.read_text()
after, count = re.subn(lock_pattern, rf'\g<1>{version}\2', before)
if count != len(lock):
    sys.exit(f"Expected {len(lock)} workspace package entries in Cargo.lock; found {count}")
if before != after:
    updates.append((lock_path, "Cargo.lock", after))
for relative, (pattern, replacement) in patterns.items():
    path = root / relative
    before = path.read_text()
    after, count = re.subn(pattern, replacement, before)
    if count != 1:
        sys.exit(f"Expected exactly one version field in {relative}; found {count}")
    if path in manifests:
        section = ""
        lines = []
        for line in after.splitlines(keepends=True):
            if line.startswith("["):
                section = line.strip()
            if "dependencies]" in section and "dev-dependencies]" not in section and "path = " in line:
                dep = tomllib.loads(line)
                spec = next(iter(dep.values()))
                if (path.parent / spec["path"]).resolve() in local_dirs:
                    line = re.sub(r'version = "[^"]+"', f'version = "={version}"', line)
            lines.append(line)
        after = "".join(lines)
    if before != after:
        updates.append((path, relative, after))

by_file = {}
for relative, pattern, least in mentions:
    by_file.setdefault(relative, []).append((pattern, least))
for relative, rules in by_file.items():
    path = root / relative
    before = path.read_text()
    after = before
    for pattern, least in rules:
        after, count = re.subn(pattern, rf"\g<1>{version}\g<2>", after)
        if count < least:
            sys.exit(f"Expected at least {least} version mention(s) in {relative} for {pattern!r}; found {count}")
    if before != after:
        updates.append((path, relative, after))

for path, relative, after in updates:
    if mode == "--write":
        path.write_text(after)
        print(f"Updated {relative}")
    else:
        print(f"Version mismatch: {relative}", file=sys.stderr)
if mode == "--write":
    go = shutil.which("go")
    if go:
        subprocess.run([go, "generate", "./..."], cwd=root / "packages/go", check=True)
        print("Ran go generate in packages/go")
    else:
        print("go not found: packages/go/api_generated.go got only its Version const; run `go generate ./...` in packages/go", file=sys.stderr)
if mode == "--check" and updates:
    sys.exit(1)
print(
    f"{len(lock)} crate versions, their Cargo.lock entries, the metadata, the Python, Go and npm package versions "
    f"and the docs release links match VERSION ({version})."
)
PYTHON
