"""README and website output examples, sliced only from real CLI captures."""
from __future__ import annotations

import shlex

PACK_LINES = 40


def render(records: list[dict]) -> str:
    """Render one shared Markdown section; only the pack tail is abbreviated."""
    by_id = {r["id"]: r for r in records}

    def run(rid: str, limit: int | None = None) -> str:
        record = by_id[rid]
        if record["exit"] != 0:
            raise ValueError(f"output example {rid} failed: {record['stderr']}")
        lines = record["stdout"].splitlines()
        if limit is not None and len(lines) > limit:
            lines = lines[:limit] + [f"… ({len(lines) - limit} more lines)"]
        return "```text\n$ " + shlex.join(record["argv"]) + "\n" + "\n".join(lines) + "\n```"

    return "\n\n".join([
        "<!-- Generated by scripts/render_readme.py from tools/website/data/demo.json. -->",
        "## What the output looks like",
        "These are real runs on the tiny [kiosk sample](tools/website/sample), captured by "
        "[capture.py](tools/website/capture.py) from the release binary. Commands run inside a copy "
        "named `kiosk`. For source builds, the executable is `dctx-cli` (or define a `dctx` alias).",
        "### Pack a project",
        "The header explains the format, the tree assigns IDs, and file blocks carry paths and line counts. "
        "The first 40 output lines follow; only the tail is omitted. `.env` is listed without its contents.",
        run("pack", PACK_LINES),
        "### Find a symbol, then read it",
        "Pass the exact ID from `find` to `read` to get its metadata and verified source bytes:",
        run("find"),
        run("read"),
        "For structured consumption, `--json` puts the same source bytes in `source_utf8` "
        "(one JSON line, shown verbatim):",
        run("read-json"),
        "### Pack for a task",
        "`--for` uses the task terms to select find results, neighbors and source reads. "
        "`--budget 800` bounds estimated output tokens, not scan size; the footer reports usage and dropped records.",
        run("pack-for"),
    ]) + "\n"
